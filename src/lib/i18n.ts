const DICTIONARIES: Record<LangCode, Record<string, string>> = { hi: HI, en: EN, mr: MR, ta: TA, bn: BN, te: TE, gu: GU, pa: PA, kn: KN, ml: ML, or: OR };

export const DEFAULT_LANG: LangCode = "en";
export const LANG_COOKIE = "fintell_lang";
export const LANG_CODES = LANGS.map((l) => l.code);

export function isLangCode(v: string | undefined | null): v is LangCode {
  return !!v && (LANG_CODES as string[]).includes(v);
}

export function getLangFromCookie(value: string | undefined | null): LangCode {
  return isLangCode(value) ? value : DEFAULT_LANG;
}

export function t(lang: LangCode, key: string): string {
  return DICTIONARIES[lang]?.[key] ?? DICTIONARIES.en[key] ?? key;
}

export function getLangInfo(code: LangCode) {
  return LANGS.find((l) => l.code === code) ?? LANGS[1];
}
